// One line under each chart title: what the test measures, then what the group divides it by.
// The divisors were worked back from data/file.json against the raw Sandra results in 2020-02/.

function measures(chart: string): { what: string, unit: string } {
  if (chart.startsWith('Processor Power Draw')) return { what: 'rated power (TDP)', unit: 'watts' }
  if (chart.startsWith('Dhrystone Aggregated')) return { what: 'combined integer score', unit: 'GOPS' }
  if (chart.startsWith('Whetstone Aggregated')) return { what: 'combined floating-point score', unit: 'GOPS' }
  if (chart.startsWith('Dhrystone Integer')) return { what: '32-bit integer instructions', unit: 'GIPS' }
  if (chart.startsWith('Dhrystone Long')) return { what: '64-bit integer instructions', unit: 'GIPS' }
  if (chart.startsWith('Whetstone Single')) return { what: 'single-precision floating-point operations', unit: 'GFLOPS' }
  if (chart.startsWith('Whetstone Double')) return { what: 'double-precision floating-point operations', unit: 'GFLOPS' }
  return { what: 'combined integer and floating-point score', unit: 'GOPS' }
}

import type { Benchmark } from './BenchChart'

// charts generated by scripts/extract.js carry their unit, and the view is the part of the group name after " - "
function describeExtracted(group: string, unit: string, lowerIsBetter: boolean) {
  const view = group.split(' - ')[1]
  const better = lowerIsBetter ? 'lower is better' : 'higher is better'
  if (view === 'Single thread') return `${unit}, one thread, ${better}`
  if (view === 'All cores') return `${unit}, every core with one thread each (no hyper-threading), ${better}`
  if (view === 'Per thread') return `${unit} per thread: the all-threads result ÷ thread count, ${better}`
  if (view === 'Per MHz') return `${unit}: the all-threads result ÷ clock speed in MHz, ${better}`
  if (view === 'Closest cores') return `${unit}, between the two cores with the fastest link, ${better}`
  if (view === 'Farthest cores') return `${unit}, between the two cores with the slowest link, ${better}`
  return `${unit}, all threads, ${better}`
}

export default function describe(group: string, benchmark: Benchmark) {
  if (benchmark.unit !== undefined) return describeExtracted(group, benchmark.unit, benchmark.lowerIsBetter ?? false)
  const chart = benchmark.name
  const { what, unit } = measures(chart)
  // the i7-14700K has no single rated TDP that matches how it ran, so its watts are measured
  if (unit === 'watts') return `${what}, in ${unit}; i7-14700K: measured wall power of the whole PC during its run`
  if (group.includes('Single thread')) return `${what}, one thread, ${unit} (billions per second)`
  if (group.includes('per thread')) return `${what}, ${unit} ÷ thread count (32, 16, 28, 28, 28, 12, 12, 4, 2)`
  if (group.includes('vs Power')) return `${what}, ${unit} ÷ rated watts × 1000 (millions per watt); i7-14700K ÷ its measured wall power`
  if (group.includes('vs Speed')) return `${what}, ${unit} ÷ clock speed in GHz`
  return `${what}, all threads, ${unit} (billions per second)`
}
